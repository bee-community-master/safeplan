const normalizedEn = Object.fromEntries(Object.entries(en).map(([key, value]) => [normalizeText(key), value]));

function normalizeText(value: string): string {
  return value.replace(/\s+/g, ' ').trim();
}

function translateConfidence(label: string): string {
  return normalizedEn[normalizeText(label)] ?? label;
}

function translateKrw(value: string): string {
  return value.replace(/(-?\d[\d,]*)원/g, (_match, amount: string) => `${amount.startsWith('-') ? '-₩' + amount.slice(1) : '₩' + amount}`);
}

